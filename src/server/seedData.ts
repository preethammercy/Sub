interface CatalogSeedSpec {
  id: string;
  slug: string;
  name: string;
  brandKey: string;
  category: SubscriptionCategory;
  description: string;
  plans: PlanOption[];
  totalSlots?: number;
  availableSlots?: number;
  features: string[];
  credLabels?: [string, string, string];
  credNote?: string;
}

function p(
  id: string,
  label: string,
  durationMonths: number,
  subsplitCostInr: number,
  sellPriceInr: number,
  retailPriceInr: number,
  badge?: string
): PlanOption {
  return {
    id,
    label,
    durationMonths,
    baseCostInr: subsplitCostInr,
    splitPriceInr: sellPriceInr,
    retailPriceInr: Math.max(sellPriceInr, retailPriceInr),
    ...(badge ? { badge } : {}),
  };
}

function buildProduct(spec: CatalogSeedSpec, nowIso: string): Product {
  const firstPlan = spec.plans[0];
  const [l1, l2, l3] = spec.credLabels || ['Account Email', 'Password', 'Profile / PIN'];
  const slugToken = spec.brandKey.replace(/[^a-z0-9]/g, '') || 'ottsub';

  return {
    id: spec.id,
    slug: spec.slug,
    name: spec.name,
    brandKey: spec.brandKey,
    category: spec.category,
    description: spec.description,
    billingCycle: firstPlan.label,
    baseCostInr: firstPlan.baseCostInr,
    splitPriceInr: firstPlan.splitPriceInr,
    retailPriceInr: firstPlan.retailPriceInr,
    plans: spec.plans,
    totalSlots: spec.totalSlots ?? 6,
    availableSlots: spec.availableSlots ?? 4,
    features: spec.features,
    active: true,
    defaultCredentials: {
      credential1: { label: l1, value: `${slugToken}.vault01@ottsub.in` },
      credential2: { label: l2, value: `Ott#${slugToken.slice(0, 4).toUpperCase()}942!` },
      credential3: { label: l3, value: 'Slot 2 · PIN 4829' },
      deliveryNote: spec.credNote || 'Follow assigned slot instructions. Do not alter master account credentials.',
    },
    createdAt: nowIso,
  };
}

